//
// Зачем. На показе нельзя вспоминать, куда нажать дальше, и нельзя, чтобы
// экран жил своей жизнью. Полоса внизу знает маршрут: «Дальше» открывает нужный
// экран, подсказка (видна только если её открыть) говорит, что сделать и что сказать.
// Состояние — в sessionStorage: переживает перезагрузку вкладки, но не остаётся
// навсегда и не мешает обычной работе в другой вкладке.

