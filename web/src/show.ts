export type ShowState = { school: string; step: number; notes: boolean };
const KEY = "lad.show";
const EVENT = "lad-show";

export function readShow(): ShowState | null {
  try {
    const raw = sessionStorage.getItem(KEY);
    return raw ? (JSON.parse(raw) as ShowState) : null;
  } catch {
    return null;
  }
}

export function writeShow(state: ShowState | null) {
  try {
    if (state) sessionStorage.setItem(KEY, JSON.stringify(state));
    else sessionStorage.removeItem(KEY);
  } catch {
    /* нет хранилища — режим показа живёт до перезагрузки */
  }
  window.dispatchEvent(new CustomEvent(EVENT, { detail: state }));
}

export function onShowChange(listener: (state: ShowState | null) => void) {
  const handler = (e: Event) => listener((e as CustomEvent<ShowState | null>).detail);
  window.addEventListener(EVENT, handler);
  return () => window.removeEventListener(EVENT, handler);
}

/** Чистая копия примера для показа. Если пример уже составляли — берём готовую
 *  сетку заготовкой, чтобы шаги после «Составления» не оказались пустыми,
 *  даже если на показе составление пропустят. */
export async function prepareShow(): Promise<string> {
  const { id } = await api.createSchool("", true);
  try {
    const schools = await api.schools();
    const solved = schools.find((s) => s.id !== id && s.schedule_at && s.name.includes("(пример)"));
    if (solved) {
      const source = await api.latest(solved.id);
      await api.saveEdited(id, source.lessons, "Заготовка для показа");
    }
  } catch {
    /* без заготовки: сетка появится на шаге «Составление» */
  }
  return id;
}
