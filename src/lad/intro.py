def show(settings: dict, on_finish) -> None:
    """Отрисовать текущий слайд. on_finish() вызывается при «Пропустить» и на конце."""
    index = st.session_state.get("intro_slide", 0)
    slide = SLIDES[index]
    last = index == len(SLIDES) - 1

    st.space("medium")
    _, middle, _ = st.columns([1, 4, 1])

    with middle:
        with st.container(border=True, key="intro_card", gap=None):
            with st.container(key="intro_badge"):
                st.markdown(f"### :material/{slide['icon']}:")
            with st.container(key="intro_step"):
                st.markdown(f":gray[Шаг {index + 1} из {len(SLIDES)}]", text_alignment="center")
            st.markdown(f"# {slide['title']}", text_alignment="center")
            st.markdown(f":gray[{slide['lead']}]", text_alignment="center")
            st.space("small")
            st.html("<div class='lad-rule'></div>")
            with st.container(key="intro_points", gap="small"):
                for number, (icon, text) in enumerate(slide["points"]):
                    # Иконка отдельной колонкой, иначе вторая строка текста
                    # заезжает под неё и абзац теряет левый край.
                    # wrap=False: иначе длинный текст переносится ПОД иконку,
                    # вместо того чтобы встать рядом с ней колонкой.
                    with st.container(horizontal=True, gap="small", wrap=False,
                                      vertical_alignment="top", key=f"point_{number}"):
                        st.markdown(f":gray[:material/{icon}:]", width="content")
                        st.markdown(text)

        st.space("small")
        dots = " ".join(":primary[●]" if n == index else ":gray[○]"
                        for n in range(len(SLIDES)))
        st.markdown(dots, text_alignment="center")
        st.space("small")

        # Кнопки по центру и по содержанию — растянутые на всю ширину читаются
        # как панель управления, а здесь всего один осмысленный шаг вперёд.
        with st.container(horizontal=True, horizontal_alignment="center", gap="medium"):
            # Без on_click: коллбэк не умеет st.rerun(), а он нужен и для перехода
            # на следующий слайд, и для выхода из интро.
            if st.button("Начать работу" if last else "Далее", type="primary",
                         icon=":material/arrow_forward:", icon_position="right",
                         key="intro_next"):
                if last:
                    on_finish()
                else:
                    st.session_state.intro_slide = index + 1
                    st.rerun()
            if st.button("Пропустить", type="tertiary", key="intro_skip"):
                on_finish()
